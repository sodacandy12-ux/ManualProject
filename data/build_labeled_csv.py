def inherit_section(df: pd.DataFrame) -> list[str]:
    """같은 분류코드 안에서만 소제목을 아래로 상속한다."""
    sections = []
    current = ""
    prev_cat = None
    for _, row in df.iterrows():
        cat = row["재난안전분류코드"]
        if cat != prev_cat:
            current = ""
            prev_cat = cat
        if not row["_has_body"]:
            current = row["제목"]
        sections.append(current)
    return sections


def build_search_text(row) -> str:
    parts = [
        f"재난대분류: {row['재난대분류']}",
        f"재난상황: {row['재난상황']}",
        f"조치단계: {row['조치단계']}",
        f"심각도: {row['심각도']} ({row['심각도설명']})",
    ]
    if row["적용장소"]:
        parts.append(f"적용장소: {row['적용장소']}")
    if row["섹션제목"] and row["섹션제목"] != row["제목"]:
        parts.append(f"섹션: {row['섹션제목']}")
    parts.append(f"제목: {row['제목']}")
    if str(row["내용"]).strip():
        parts.append(f"행동요령: {row['내용']}")
    return "\n".join(parts)


