def infer_disaster(cat: str, title: str, section: str) -> str:
    blob = f"{title} {section}"
    for key, label in DISASTER_KEYWORDS:
        if key not in blob:
            continue
        if key in GENERIC_DISASTER_KEYS and cat in SKIP_GENERIC_IF_CAT:
            continue
        return label
    if cat == "47000028":
        if any(x in blob for x in ("가스", "LPG", "LNG", "부탄")):
            return "가스사고"
        return "전기사고"
    if cat in CAT_DISASTER:
        return CAT_DISASTER[cat]
    if "유도선" in title or "사고발생" in title:
        return "유도선"
    return "기타"


