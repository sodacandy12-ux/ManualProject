def norm_code(v):
    if pd.isna(v) or str(v).strip() == "" or str(v).lower() == "nan":
        return ""
    if isinstance(v, float):
        return str(int(v)) if v == int(v) else str(v).rstrip("0").rstrip(".")
    s = str(v).strip()
    try:
        f = float(s)
        if f == int(f):
            return str(int(f))
    except ValueError:
        return s
    return s


def is_generic_title(title: str) -> bool:
    t = title.strip()
    if t[:1].isdigit() and "." in t[:4]:
        return True
    return any(m in t for m in GENERIC_TITLE_MARKERS)


